#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <numbers>
#include <stdexcept>

namespace
{
constexpr unsigned resolution = 65;
constexpr unsigned sampleCount = 65536;
struct Vector
{
	double mX, mY, mZ;
};
Vector normalize(Vector v)
{
	const double inverse = 1 / std::sqrt(v.mX * v.mX + v.mY * v.mY + v.mZ * v.mZ);
	return {v.mX * inverse, v.mY * inverse, v.mZ * inverse};
}
double radicalInverse(uint32_t bits)
{
	bits = (bits << 16) | (bits >> 16);
	bits = ((bits & 0x55555555u) << 1) | ((bits & 0xaaaaaaaau) >> 1);
	bits = ((bits & 0x33333333u) << 2) | ((bits & 0xccccccccu) >> 2);
	bits = ((bits & 0x0f0f0f0fu) << 4) | ((bits & 0xf0f0f0f0u) >> 4);
	bits = ((bits & 0x00ff00ffu) << 8) | ((bits & 0xff00ff00u) >> 8);
	return (static_cast<double>(bits) + 0.5) / 4294967296.0;
}
double energyLoss(double roughness, double noV)
{
	if (roughness == 0 || noV == 0)
	{
		return 0;
	}
	const double alpha = std::pow(std::max(roughness, 0.02), 2);
	const double a2 = alpha * alpha;
	const double vx = std::sqrt(std::max(0.0, 1 - noV * noV));
	const Vector stretched = normalize({alpha * vx, 0, noV});
	const double sqrtV = std::sqrt(a2 + (1 - a2) * noV * noV);
	double loss = 0;
	for (unsigned i = 0; i < sampleCount; ++i)
	{
		const double radius = std::sqrt((i + 0.5) / sampleCount);
		const double phi = 2 * std::numbers::pi * radicalInverse(i);
		const double x = radius * std::cos(phi);
		double y = radius * std::sin(phi);
		const double blend = 0.5 * (1 + stretched.mZ);
		y = (1 - blend) * std::sqrt(std::max(0.0, 1 - x * x)) + blend * y;
		const double z = std::sqrt(std::max(0.0, 1 - x * x - y * y));
		// For V in the XZ plane use T1=(0,1,0), T2=(-Vh.z,0,Vh.x).
		const Vector h = normalize({alpha * (-y * stretched.mZ + z * stretched.mX), alpha * x,
			std::max(0.0, y * stretched.mX + z * stretched.mZ)});
		const double voH = vx * h.mX + noV * h.mZ;
		const double noL = 2 * voH * h.mZ - noV;
		double weight = 0;
		if (noL > 0)
		{
			const double sqrtL = std::sqrt(a2 + (1 - a2) * noL * noL);
			// F=1: f_ss * NoL / PDF_VNDF for height-correlated Smith GGX.
			weight = noL * (noV + sqrtV) / (noL * sqrtV + noV * sqrtL);
		}
		loss += 1 - weight;
	}
	return std::clamp(loss / sampleCount, 0.0, 1.0);
}
}
int main(int count, char** arguments)
{
	try
	{
		if (count != 2)
		{
			throw std::runtime_error("Usage: GgxEnergyLut <output.h>");
		}
		std::array<double, resolution * resolution + resolution> lut{};
		for (unsigned row = 0; row < resolution; ++row)
		{
			for (unsigned column = 0; column < resolution; ++column)
			{
				const double x = static_cast<double>(column) / (resolution - 1);
				lut[row * resolution + column] = energyLoss(static_cast<double>(row) / (resolution - 1), x * x);
			}
			// Integrate the interpolated LUT itself so the compensation lobe is normalized.
			double average = 0;
			constexpr unsigned quadratureCount = 16384;
			for (unsigned i = 0; i < quadratureCount; ++i)
			{
				const double mu = (i + 0.5) / quadratureCount;
				const double x = std::sqrt(mu) * (resolution - 1);
				const unsigned column = std::min(static_cast<unsigned>(x), resolution - 2);
				const double value = std::lerp(lut[row * resolution + column], lut[row * resolution + column + 1], x - column);
				average += 2 * mu * value / quadratureCount;
			}
			lut[resolution * resolution + row] = average;
		}
		std::ofstream file(arguments[1]);
		file << "// Generated by tools/GgxEnergyLut; 65x65 nodes: roughness, sqrt(NoV).\n"
			<< "// F=1 height-correlated GGX loss, followed by 65 cosine-weighted row averages.\n"
			<< "#pragma once\n#include <array>\ninline constexpr std::array<float, " << lut.size() << "> ggxEnergyLut{\n";
		file << std::scientific << std::setprecision(9);
		for (size_t i = 0; i < lut.size(); ++i)
		{
			file << (i % 5 == 0 ? "\t" : " ") << lut[i] << "f," << (i % 5 == 4 ? "\n" : "");
		}
		file << "\n};\n";
		if (!file)
		{
			throw std::runtime_error("Cannot write LUT header.");
		}
		std::cout << "Generated " << lut.size() << " values with " << sampleCount << " samples/node.\n";
		return 0;
	}
	catch (const std::exception& error)
	{
		std::cerr << error.what() << '\n';
		return 1;
	}
}
